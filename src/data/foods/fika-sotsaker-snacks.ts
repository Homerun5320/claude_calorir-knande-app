/**
 * Fika, bakverk, sötsaker, glass & dessert samt snacks.
 *
 * Grova linjer: en rad per vardagsbegrepp så som det köps och äts. Svenska fikaklassiker behålls
 * (kanelbulle, kardemummabulle, semla, kladdkaka, prinsesstårta, chokladboll, dammsugare, mazarin
 * …), medan varianter med nästan samma näringsvärde delar rad – bageribulle och hembakad bulle,
 * vanilj- och chokladmuffins, sju sorters småkakor, ljus och mörk sirap, sylt av olika bär. Sökorden
 * och anteckningen talar om vad som ingår.
 *
 * Samlingsvärden (`avg`): produkttyper med många märken – choklad, chokladbars, lösgodis, chips,
 * popcorn, glass, kex, proteinbars, müslibars m.fl. – anges som ett genomsnitt av förpackningsuppgifter
 * för vanliga märken i svenska butiker, avstämt mot Livsmedelsverkets generiska poster, eller som
 * Livsmedelsverkets värde för produkttypen när det motsvarar vanliga märken (då står det i
 * anteckningen). Märkesnamnen finns som sökord, men inga rader har `brand`. Exakta värden för ett
 * visst märke fås med streckkodsläsaren (Open Food Facts).
 *
 * Värden per 100 g ätlig del, baserade på Livsmedelsverkets livsmedelsdatabas (bakverk, godis,
 * glass, sylt) och typiska svenska förpackningsuppgifter. Hembakat är beräknat från klassiska
 * svenska recept (t.ex. sockerkaka, småkakor). Vitaminer och mineraler i sammansatta bakverk är
 * uppskattade utifrån ingredienserna. Margarin i konsumentförpackning är berikat med vitamin D
 * (20 µg/100 g), men bagerimargarin och mjölk som används industriellt är det oftast inte – därför
 * är vitamin D i bageribakverk och färdiga desserter försiktigt satt.
 *
 * Livsmedel med `lmv` är samma livsmedel (samma tillagning) som i Livsmedelsverkets databas och har
 * dess värden för energi och makronäringsämnen; övriga näringsämnen fylls i därifrån. Det gäller även
 * samlingsvärden som bygger på Livsmedelsverkets värde för produkttypen. Egna medelvärden av flera
 * sorter eller märken saknar koppling. Undantag: honung har tillsatt socker = sockerarter, eftersom
 * honung räknas som fritt socker (NNR 2023).
 *
 * Portioner: vanliga svenska storlekar – bageribulle, bit av kaka skuren i 12 bitar,
 * kula glass (ca 50 g), handfull lösgodis (ca 30 g) osv.
 */
