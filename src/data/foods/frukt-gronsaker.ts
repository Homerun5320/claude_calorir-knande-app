/**
 * Frukt, bär, grönsaker, svamp, rotfrukter, potatis och baljväxter.
 *
 * Grova linjer: en rad per vardagsbegrepp så som det äts ("Äpple", "Paprika", "Lök", "Linser").
 * Sorter med nästan samma näringsvärde delar rad (äppelsorter, röd/grön/gul paprika, gul lök och
 * rödlök, kidneybönor/svarta/vita bönor, gröna och röda linser) – sökorden och anteckningen talar om
 * vilka som ingår. Körsbärstomat, vattenmelon och liknande har egna rader eftersom portionerna skiljer
 * sig.
 *
 * Värden per 100 g ätlig del (utan skal, kärnhus och kärnor om inget annat anges), i första hand
 * enligt Livsmedelsverkets livsmedelsdatabas eller väletablerade typvärden för råvaran. Livsmedel
 * med `lmv` är samma livsmedel (samma tillagning) som Livsmedelsverkets post med det numret och har
 * dess makronäringsvärden (eller ett medelvärde av sorterna som ingår); övriga näringsämnen fylls i
 * därifrån. Vitamin A anges som retinolekvivalenter (1 µg RE = 12 µg betakaroten, som i NNR).
 *
 * Frukt, bär och grönsaker anges råa – så som de oftast äts eller vägs. Potatis anges kokt (vikten
 * ändras knappt vid kokning, så rå potatis kan vägas direkt). Torkade baljväxter anges kokta; den som
 * väger dem torra väljer "g torkad" eller "dl torkad" – `raw` anger hur många gram kokta bönor ett
 * gram torkade blir (energin per 100 g torkade delat med energin per 100 g kokta, enligt
 * Livsmedelsverkets poster). Konserverade bönor, kikärtor och linser räknas som kokta.
 *
 * Produkttyper med många märken (äppelmos, konserverad frukt, inlagd gurka, frysta
 * grönsaksblandningar, pommes frites …) är samlingsvärden (`avg`): typvärden för vanliga märken i
 * svenska butiker. De bygger på Livsmedelsverkets generiska poster (som ofta är marknadsvägda) och
 * typiska förpackningsuppgifter. Exakta värden för ett visst märke fås med streckkodsläsaren.
 * Borttagna och sammanslagna id:n har alias i `aliases/frukt-gronsaker.ts`.
 *
 * Kategorier enligt kostråden: potatis räknas inte till frukt och grönt, sötpotatis räknas som
 * rotfrukt och baljväxter (bönor, linser, torkade ärter, edamame) är ett eget råd sedan 2025.
 * Gröna ärtor, sockerärtor och haricots verts räknas som grönsaker.
 */
